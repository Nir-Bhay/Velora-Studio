// The film as a Remotion composition.
//
// One <canvas> is redrawn on every frame by the shared drawing code in film/frame.mjs, so the editor
// shows exactly what the ffmpeg renderer produces. The narration mix is one <Audio> track. Each scene
// is a <Sequence> so the timeline shows the scene names and times.
import React, {useEffect, useLayoutEffect, useRef, useState} from 'react';
import {AbsoluteFill, Audio, Sequence, continueRender, delayRender, staticFile, useCurrentFrame, useVideoConfig} from 'remotion';
// The drawing code is plain ES modules shared with the Node renderer, so it has no TypeScript types.
// @ts-ignore
import {drawFilmFrame, makeGrainTile} from '../../film/frame.mjs';
// @ts-ignore: generated by render/prepare.mjs
import timing from '../../out/timing.json';
import {loadFonts} from './fonts';

const W = 1080;
const H = 1920;

// Offscreen canvas factory for the grain tile, in the browser.
const makeCanvas = (w: number, h: number): HTMLCanvasElement => {
  const c = document.createElement('canvas');
  c.width = w;
  c.height = h;
  return c;
};

export const Film: React.FC = () => {
  const frame = useCurrentFrame();
  const {fps} = useVideoConfig();
  // Hold the first render until the fonts and the grain tile are ready, so the export never sees a fallback font.
  const [handle] = useState(() => delayRender('loading fonts'));
  const [ready, setReady] = useState(false);
  const canvasRef = useRef<HTMLCanvasElement>(null);
  const grainRef = useRef<HTMLCanvasElement | null>(null);

  useEffect(() => {
    loadFonts()
      .then(() => {
        grainRef.current = makeGrainTile(makeCanvas);
        setReady(true);
        continueRender(handle);
      })
      .catch((err) => {
        console.error('font load failed', err);
        continueRender(handle);
      });
  }, [handle]);

  // Draw synchronously after each frame change. Remotion captures the canvas after this runs.
  useLayoutEffect(() => {
    const c = canvasRef.current;
    if (!c || !ready) return;
    const ctx = c.getContext('2d');
    if (!ctx) return;
    drawFilmFrame(ctx, frame / fps, timing, {grain: grainRef.current, W, H, total: timing.total});
  }, [frame, fps, ready]);

  return (
    <AbsoluteFill style={{background: '#0B1120'}}>
      <canvas ref={canvasRef} width={W} height={H} style={{width: '100%', height: '100%'}} />
      {timing.scenes.map((s: any) => (
        <Sequence
          key={s.id}
          name={`S${s.id} ${s.name} ${s.start.toFixed(2)}–${(s.start + s.duration).toFixed(2)}s`}
          from={Math.round(s.start * fps)}
          durationInFrames={Math.round(s.duration * fps)}
          layout="none"
        >
          {null}
        </Sequence>
      ))}
      <Audio src={staticFile('audio/mix.wav')} />
    </AbsoluteFill>
  );
};
